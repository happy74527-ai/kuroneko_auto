INSTRUCTIONS = ("The state is quiz text read from a phone screen (Chinese, Japanese or English). "
                "Which option is the correct answer to the quiz question?")


def ask(question, options, mode):
    body = {"state": question, "bank_mode": mode, "online": False,
            "questions": {"answer": {"type": "choice", "instructions": INSTRUCTIONS,
                                     "criteria": {chr(65 + i): o for i, o in enumerate(options)}}}}
    req = urllib.request.Request(URL, json.dumps(body).encode(), {"Content-Type": "application/json"})
    with urllib.request.urlopen(req, timeout=60) as r:
        res = json.load(r)
    a = res["answers"]["answer"]
    return options[ord(a["choice"]) - 65], a.get("confidence", 0.0), res.get("source"), res.get("latency_ms")


def main():
    for mode in ["d3", "no_hint", "full"]:
        ok = 0
        sources = {}
        lat = []
        for q, opts, truth in CASES:
            pick, conf, src, ms = ask(q, opts, mode)
            ok += pick == truth
            sources[src] = sources.get(src, 0) + 1
            lat.append(ms)
            if mode == "full":
                print(f"  {'✓' if pick == truth else '✗'} {src:<8} conf={conf:.2f} {q[:24]} → {pick}")
        print(f"[{mode}] {ok}/{len(CASES)} 正確  來源 {sources}  平均 {sum(lat) / len(lat):.0f}ms")


if __name__ == "__main__":
    main()
